def render(rows, palette, shadow):
    """palette maps each art character to its color; '.' is the blank slot showing through"""
    img = base.copy()
    px = img.load()
    cells = {(x, y): palette[ch] for y, row in enumerate(rows) for x, ch in enumerate(row) if ch != "."}
    for x, y in cells:  # shadow first, one pixel down-right
        if (x + 1, y + 1) not in cells:
            px[x + 1, y + 1] = shadow
    for (x, y), color in cells.items():
        px[x, y] = color
    return img

for name, (art, palette, shadow) in GLYPHS.items():
    rows = art.strip("\n").split("\n")
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), name
    render(rows, palette, shadow).save(tex + name + ".png")
    if name == "ui_arrow_left":
        right = [r[::-1] for r in rows]
        # mirror the glyph but keep the shadow falling down-right
        render(right, palette, shadow).save(tex + "ui_arrow_right.png")
